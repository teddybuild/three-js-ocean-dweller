// open-water's sky (src/sky/sky.js) and the LUT lookups of SKY_LOOKUP_GLSL (src/sky/atmosphere.js) in TSL: sky
// radiance, transmittance, aerial perspective, irradiance, stars, the sun and moon disk, the equirectangular
// reflection environment (with its mip chain) and its irradiance, both with the clouds composited (M4). Fog, rain
// curtains and crepuscular rays come with milestone 5.
import * as THREE from 'three/webgpu';
import * as TSL from 'three/tsl';
import { atmoU, AtmosphereCompute } from './atmosphere';

type Node = any; // @types/three's TSL overloads reject long node chains, so nodes and TSL functions are untyped
const {
  Fn, Loop, uniform, float, int, vec2, vec3, vec4, uvec2, select, sqrt, pow, exp, log, abs, cos, sin, acos, asin, atan,
  clamp, mix, smoothstep, max, min, normalize, dot, cross, sign, textureStore, texture, instanceIndex, floor, fract,
  fwidth, ivec2,
} = TSL as any;

const PI = Math.PI;
const SUN_COS = 0.99998917; // cos(0.2666 deg)

export const skyU = {
  sunVis: uniform(1), isMoon: uniform(0), pixelAngle: uniform(0.001), time: uniform(0),
  cloudsOn: uniform(0), cloudSize: uniform(new THREE.Vector2(1, 1)),
  envRrs: uniform(new THREE.Vector3(0.0004, 0.003, 0.0085)), // the sea's water-leaving reflectance (1/sr)
};

const envTexture = (w: number, h: number, repeatS: boolean) => {
  const t = new THREE.StorageTexture(w, h);
  t.type = THREE.HalfFloatType;
  t.generateMipmaps = true; // generated by three when the texture is next sampled after a store
  t.minFilter = THREE.LinearMipmapLinearFilter;
  if (repeatS) t.wrapS = THREE.RepeatWrapping; // wrap in azimuth (seam at 180 deg), clamp in elevation
  return t;
};

function starHash(p0: Node) {
  const p = fract(p0.mul(vec3(0.1031, 0.103, 0.0973))).toVar();
  p.addAssign(dot(p, p.yxz.add(33.33)));
  return fract(p.x.add(p.y).mul(p.z));
}
const mhash = (p: Node) => fract(sin(dot(p, vec2(127.1, 311.7))).mul(43758.5453));
function mnoise(p: Node) {
  const i = floor(p).toVar(), f0 = fract(p).toVar();
  const f = f0.mul(f0).mul(f0.mul(-2).add(3)).toVar();
  return mix(mix(mhash(i), mhash(i.add(vec2(1, 0))), f.x), mix(mhash(i.add(vec2(0, 1))), mhash(i.add(vec2(1, 1))), f.x), f.y);
}
const equirectUv = (d: Node) => vec2(atan(d.z, d.x).div(2 * PI).add(0.5), acos(clamp(d.y, -1, 1)).div(PI));

export class SkyCompute {
  env = Object.assign(envTexture(512, 256, true), { anisotropy: 16 }); // (GL: aniso 16, the water's streak blur)
  envDeck = envTexture(512, 256, false); // the same without rain and mist: the light entering them
  // the cloud passes' outputs (ping-pong: the caller sets .value every frame, see setClouds)
  private blank = (() => { const t = new THREE.StorageTexture(1, 1); t.type = THREE.HalfFloatType; return t; })();
  cloudsEnv = texture(this.blank);
  clouds = texture(this.blank);
  irradiance = (() => { const t = new THREE.StorageTexture(2, 1); t.type = THREE.HalfFloatType; t.minFilter = t.magFilter = THREE.NearestFilter; return t; })();
  private renderer: THREE.WebGPURenderer;
  private atmo: AtmosphereCompute;
  private envNode: Node;
  private irrNode: Node;

  constructor(renderer: THREE.WebGPURenderer, atmo: AtmosphereCompute) {
    this.renderer = renderer;
    this.atmo = atmo;
    this.envNode = this.envKernel();
    this.irrNode = this.irrKernel();
  }

  skyIrradiance() { return texture(this.irradiance, vec2(0.25, 0.5)).level(0).rgb; }
  // irradiance of the sky and clouds alone (the light that enters the rain and mist below the deck)
  deckIrradiance() { return texture(this.irradiance, vec2(0.75, 0.5)).level(0).rgb; }

  private sunBasisAz(d: Node) {
    const sunH = normalize(vec3(atmoU.sun.x, 0, atmoU.sun.z).add(vec3(1e-6, 0, 0))).toVar();
    const sunR = normalize(cross(vec3(0, 1, 0), sunH));
    return vec2(dot(d, sunH), dot(d, sunR));
  }

  skyRadiance(d: Node) {
    const h = this.sunBasisAz(d).toVar();
    const az = abs(atan(h.y, h.x)).div(PI);
    const el = asin(clamp(d.y, -1, 1)).div(PI / 2).toVar();
    const v = sign(el).mul(sqrt(abs(el)));
    return texture(this.atmo.skyView, vec2(az, v.mul(0.5).add(0.5))).level(0).rgb.mul(atmoU.lightScale);
  }

  // in-scattered radiance L and transmittance T of the sea-level haze over distKm along d
  aerial(d: Node, distKm: Node) {
    const h = this.sunBasisAz(d).toVar();
    const uv = vec2(abs(atan(h.y, h.x)).div(PI), sqrt(clamp(distKm.div(atmoU.maxDist), 0, 1)));
    const al = texture(this.atmo.aerialL, uv).level(0).toVar();
    const T = exp(al.a.negate().mul(atmoU.extRatio)).toVar();
    // under a cloud deck the haze is lit by diffuse light from the cloud base, not the sun: per channel, in an
    // isotropic diffuse field the haze takes the field's own colour (no warm band at the horizon)
    const L = al.rgb.mul(atmoU.lightScale).mul(atmoU.hazeSun)
      .add(T.oneMinus().mul(this.deckIrradiance()).mul(0.9 / (2 * 3.14159)).mul(atmoU.hazeSun.oneMinus()));
    return { L, T };
  }

  transmittanceAt(hKm: Node, mu0: Node) {
    const Rg = 6360.0, Rt = 6460.0, H = Math.sqrt(Rt * Rt - Rg * Rg);
    const mu = float(mu0).toVar();
    const r = max(hKm, 0.0005).add(Rg).toVar();
    const rho = sqrt(max(0, r.mul(r).sub(Rg * Rg))).toVar();
    const disc = r.mul(r).mul(mu.mul(mu).sub(1)).add(Rt * Rt);
    const d = max(0, r.negate().mul(mu).add(sqrt(max(disc, 0))));
    const dmin = float(Rt).sub(r), dmax = rho.add(H);
    const sinH = float(Rg).div(r);
    const cosH = sqrt(max(0, sinH.mul(sinH).oneMinus())).negate().toVar();
    const fade = smoothstep(cosH.sub(0.004), cosH.add(0.004), mu);
    return texture(this.atmo.transmittance, vec2(d.sub(dmin).div(dmax.sub(dmin)), rho.div(H))).level(0).rgb.mul(fade);
  }

  // illuminance of the light source (sun, or moon at night) at the camera
  sunIlluminance() { return this.transmittanceAt(atmoU.camH, atmoU.sun.y).mul(atmoU.lightScale); }

  // Night sky: stars as points with physical flux (magnitude m -> 10^(-0.4 (m + 26.74)) of the sun), N(<m) ~ 10^(0.5 m)
  // down to m = 6.5, spread over one pixel by a gaussian PSF, extinguished by the atmosphere and scintillating near
  // the horizon; plus the Milky Way. Against a daylight sky they vanish on their own.
  starField(d: Node) {
    const K = 150.0;
    const base = floor(d.mul(K).sub(0.5)).toVar();
    const acc = vec3(0).toVar();
    const sigma = skyU.pixelAngle.mul(0.75).toVar();
    Loop(8, ({ i }: Node) => {
      const cell = base.add(vec3(float(i.bitAnd(1)), float(i.shiftRight(1).bitAnd(1)), float(i.shiftRight(2).bitAnd(1)))).toVar();
      const sp = normalize(cell.add(0.15).add(vec3(starHash(cell.add(11.1)), starHash(cell.add(23.7)), starHash(cell.add(37.3))).mul(0.7))).toVar();
      const x = cross(sp, d).toVar();
      const ang2 = dot(x, x).toVar();
      // a star exists in 14% of cells, only if its projection stays in its own cell (the search covers +-1/2 cell)
      const keep = starHash(cell).lessThanEqual(0.14)
        .and(dot(abs(floor(sp.mul(K)).sub(cell)), vec3(1)).lessThan(0.5))
        .and(ang2.lessThanEqual(sigma.mul(sigma).mul(36)));
      const m = log(max(starHash(cell.add(5.3)), 1e-5)).mul(2 / Math.log(10)).add(6.5);
      const flux = pow(float(10), m.sub(atmoU.lightMag).mul(-0.4));
      const psf = exp(ang2.mul(-0.5).div(sigma.mul(sigma))).div(sigma.mul(sigma).mul(6.2832));
      const col = mix(vec3(1.0, 0.78, 0.55), vec3(0.78, 0.86, 1.0), smoothstep(0.1, 0.9, starHash(cell.add(71.9))));
      const twinkle = starHash(cell.add(floor(skyU.time.mul(18)))).sub(0.5).mul(0.55).mul(exp(max(d.y, 0).mul(-12))).add(1);
      acc.addAssign(select(keep, col.mul(flux).mul(psf).mul(twinkle), vec3(0)));
    });
    // Milky Way: a band of unresolved stars with dark dust lanes
    const b = dot(d, normalize(vec3(0.42, 0.55, -0.72))).toVar();
    const band = exp(b.mul(b).negate().div(0.035));
    const n = starHash(floor(d.mul(60))).mul(0.35).add(0.65);
    const dust = smoothstep(0, 0.08, abs(b.add(sin(d.x.mul(9).add(d.z.mul(5))).mul(0.03))));
    acc.addAssign(vec3(0.85, 0.88, 1.0).mul(band).mul(n).mul(mix(0.35, 1.0, dust)).mul(2.5e-10).mul(pow(float(10), atmoU.lightMag.add(26.74).mul(0.4))));
    return select(d.y.lessThan(-0.01), vec3(0), acc.mul(this.transmittanceAt(float(0), max(d.y, 0))));
  }

  // the clear-sky background of SKY_FS for view direction d: sky, stars, and the sun (limb-darkened) or moon disk
  background(d0: Node) {
    const d = normalize(d0).toVar();
    const sun = atmoU.sun;
    const c = dot(d, sun).toVar();
    const wEdge = skyU.pixelAngle.mul(0.00465).toVar();
    const mu = sqrt(max(0, c.oneMinus().div(1 - SUN_COS).oneMinus())).toVar();
    // limb darkening I(mu) = mu^a (Neckel & Labs), normalised so the disk carries the full illuminance
    const a = vec3(0.397, 0.503, 0.652);
    const limbSun = pow(max(vec3(mu), vec3(1e-6)), a).mul(a.mul(0.5).add(1));
    // the moon: no limb darkening, darker maria (albedo ~0.07 vs ~0.12 highlands)
    const t1 = normalize(cross(sun, vec3(0, 1, 0))).toVar();
    const q = vec2(dot(d.sub(sun), t1), dot(d.sub(sun), cross(t1, sun))).div(0.00465).toVar();
    const maria = mnoise(q.mul(2.2).add(3.1)).mul(0.6).add(mnoise(q.mul(5)).mul(0.3)).add(mnoise(q.mul(11)).mul(0.1));
    const limb = select(skyU.isMoon.greaterThan(0.5), vec3(mix(1.15, 0.62, smoothstep(0.45, 0.62, maria))), limbSun);
    const edge = smoothstep(wEdge.negate().add(SUN_COS), wEdge.add(SUN_COS), c);
    const disk = this.sunIlluminance().mul(skyU.sunVis).div(6.8e-5).mul(limb).mul(edge);
    return this.skyRadiance(d).add(this.starField(d)).add(select(c.greaterThan(wEdge.negate().add(SUN_COS)), disk, vec3(0)));
  }

  // the background of SKY_FS with the clouds composited; uv: screen uv with v up (GL's vUv). Fog and shafts: M5.
  backgroundWithClouds(d0: Node, uv: Node) {
    const d = normalize(d0).toVar();
    const col = this.background(d).toVar();
    // a low-resolution buffer is upsampled with Catmull-Rom (sharp: a tent or bilinear filter smears the billows into
    // mush), clamped to the four nearest texels so edges cannot ring
    const cts = skyU.cloudSize;
    const lowRes = cts.x.lessThan(256 * 4).and(cts.x.mul(1.5).lessThan(float(1).div(max(fwidth(uv.x), 1e-6)))).toVar();
    const cl = select(lowRes, this.cloudBicubic(uv, cts), this.clouds.sample(uv).level(0)).toVar();
    const sky = this.skyRadiance(d).toVar();
    const skyCol = sky.add(col.sub(sky).mul(cl.a).mul(cl.a));
    return select(skyU.cloudsOn.greaterThan(0.5), skyCol.mul(cl.a).add(cl.rgb), col);
  }

  private cloudBicubic(uv: Node, size: Node) {
    const sp = uv.mul(size).sub(0.5).toVar();
    const tp = floor(sp).add(0.5);
    const f = sp.sub(floor(sp)).toVar();
    const w0 = f.mul(f.mul(f.mul(-0.5).add(1)).sub(0.5));
    const w1 = f.mul(f).mul(f.mul(1.5).sub(2.5)).add(1);
    const w2 = f.mul(f.mul(f.mul(-1.5).add(2)).add(0.5)).toVar();
    const w3 = f.mul(f).mul(f.mul(0.5).sub(0.5));
    const w12 = w1.add(w2).toVar();
    const t0 = tp.sub(1).div(size).toVar(), t3 = tp.add(2).div(size).toVar(), t12 = tp.add(w2.div(w12)).div(size).toVar();
    const tx = (u: Node) => this.clouds.sample(u).level(0);
    const r = tx(vec2(t12.x, t0.y)).mul(w12.x.mul(w0.y))
      .add(tx(vec2(t0.x, t12.y)).mul(w0.x.mul(w12.y))).add(tx(t12).mul(w12.x.mul(w12.y))).add(tx(vec2(t3.x, t12.y)).mul(w3.x.mul(w12.y)))
      .add(tx(vec2(t12.x, t3.y)).mul(w12.x.mul(w3.y)))
      .div(w12.x.mul(w0.y).add(w0.x.mul(w12.y)).add(w12.x.mul(w12.y)).add(w3.x.mul(w12.y)).add(w12.x.mul(w3.y)));
    const ip = ivec2(floor(sp)).toVar();
    const mx = ivec2(size).sub(1);
    const ld = (o: number[]) => this.clouds.load(clamp(ip.add(ivec2(o[0], o[1])), ivec2(0), mx)).level(int(0));
    const a = ld([0, 0]).toVar(), b = ld([1, 0]).toVar(), c = ld([0, 1]).toVar(), e = ld([1, 1]).toVar();
    return clamp(r, min(min(a, b), min(c, e)), max(max(a, b), max(c, e)));
  }

  private envKernel() {
    const env = this.env, envDeck = this.envDeck;
    return Fn(() => {
      const x = instanceIndex.mod(512), y = instanceIndex.div(512);
      const uv = vec2(float(x).add(0.5).div(512), float(y).add(0.5).div(256)).toVar();
      const phi = uv.x.sub(0.5).mul(2 * PI).toVar();
      // below the horizon: the mirrored direction (see the end)
      const dy0 = cos(uv.y.mul(PI)).toVar();
      const theta = min(uv.y, uv.y.oneMinus()).mul(PI).toVar();
      const d = normalize(vec3(cos(phi).mul(sin(theta)), cos(theta), sin(phi).mul(sin(theta))).add(vec3(0, 0.002, 0))).toVar();
      const col = this.skyRadiance(d).toVar();
      const vUp = min(uv.y, uv.y.oneMinus());
      const cl = this.cloudsEnv.sample(vec2(uv.x, min(vUp, 0.5 - 0.6 / 160))).level(0).toVar();
      col.assign(select(skyU.cloudsOn.greaterThan(0.5), col.mul(cl.a).add(cl.rgb), col));
      // A ray reflected below the horizon meets the next wave nearby and sees that wave: the sky mirrored by its Fresnel
      // reflectance and its water. This half only feeds the mip chain, whose wide blur on a rough sea must not average
      // in the haze glare that hugs the horizon.
      const Fs = pow(min(dy0.negate().add(0.12), 1).oneMinus(), 5).mul(0.98).add(0.02).toVar();
      const Ed = this.sunIlluminance().mul(skyU.sunVis).mul(max(atmoU.sun.y, 0)).add(this.skyIrradiance());
      const sea = Fs.mul(col).add(Fs.oneMinus().mul(skyU.envRrs).mul(Ed));
      const out = vec4(select(dy0.lessThan(0), sea, col), 1).toVar();
      textureStore(env, uvec2(x, y), out);
      textureStore(envDeck, uvec2(x, y), out); // (no rain or mist yet: the deck light equals the environment)
    })().compute(512 * 256);
  }

  // cosine-weighted hemisphere integral of the environment (sky + clouds); texel 1: without rain and mist
  private irrKernel() {
    const irr = this.irradiance;
    return Fn(() => {
      const E = vec3(0).toVar();
      const deck = instanceIndex.equal(1);
      Loop(16, 6, ({ i, j }: Node) => {
        const phi = float(i).add(0.5).mul(2 * PI / 16);
        const ct = float(j).add(0.5).div(6).toVar(); // uniform in cos(theta)
        const st = sqrt(ct.mul(ct).oneMinus());
        const uv = equirectUv(vec3(cos(phi).mul(st), ct, sin(phi).mul(st))).toVar();
        E.addAssign(select(deck, texture(this.envDeck, uv).level(4).rgb, texture(this.env, uv).level(4).rgb).mul(ct));
      });
      // E = integral L cos dOmega = 2 pi * mean(L cos) for samples uniform in cos(theta)
      textureStore(irr, uvec2(instanceIndex, 0), vec4(E.mul(2 * PI / 96), 1));
    })().compute(2);
  }

  // env, then (a separate submit, so three's mip generation runs between them) its irradiance
  renderEnv() {
    this.renderer.compute(this.envNode);
    this.renderer.compute(this.irrNode);
  }
}

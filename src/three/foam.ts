// open-water's foam (src/ocean/foam.js) in TSL: FoamTexture's procedural, tileable 1024 x 1024 structure as a compute
// kernel (texel (x, y) is GL's vUv = ((x + 0.5) / size, (y + 0.5) / size)), and FOAM_GLSL's foamCoverage over TSL
// nodes. R: marbling threshold, G: fine bubble texture, B: wind streak field (along +x = downwind), A: lace network.
import * as THREE from 'three/webgpu';
import * as TSL from 'three/tsl';

type Node = any; // @types/three's TSL overloads reject long node chains, so nodes and TSL functions are untyped
const {
  Fn, Loop, If, float, vec2, vec4, uvec2, select, sqrt, pow, exp, abs, sin, clamp, mix, smoothstep, max, min, length, dot,
  textureStore, texture, instanceIndex, floor, fract, dFdx, dFdy, fwidth,
} = TSL as any;

const hash2 = (p: Node) => fract(sin(vec2(dot(p, vec2(127.1, 311.7)), dot(p, vec2(269.5, 183.3)))).mul(43758.5453));

// periodic gradient noise in [-1, 1]
function gnoise(x: Node, P: Node) {
  const i = floor(x).toVar(), f = fract(x).toVar();
  const u = f.mul(f).mul(f).mul(f.mul(f.mul(6).sub(15)).add(10)).toVar();
  const a = dot(hash2(i.mod(P)).mul(2).sub(1), f);
  const b = dot(hash2(i.add(vec2(1, 0)).mod(P)).mul(2).sub(1), f.sub(vec2(1, 0)));
  const c = dot(hash2(i.add(vec2(0, 1)).mod(P)).mul(2).sub(1), f.sub(vec2(0, 1)));
  const d = dot(hash2(i.add(vec2(1, 1)).mod(P)).mul(2).sub(1), f.sub(vec2(1, 1)));
  return mix(mix(a, b, u.x), mix(c, d, u.x), u.y).mul(1.6);
}

// fbm (gain 0.5) and ridged (gain 0.55, |noise|) octave sums over oct octaves, normalised by the amplitude sum
function octaves(x0: Node, P0: Node, oct: number, gain: number, ridge: boolean) {
  const s = float(0).toVar(), a = float(0.5).toVar(), n = float(0).toVar();
  const x = vec2(x0).toVar(), P = vec2(P0).toVar();
  Loop(oct, () => {
    const g = gnoise(x, P);
    s.addAssign(a.mul(ridge ? abs(g) : g));
    n.addAssign(a);
    x.mulAssign(2);
    P.mulAssign(2);
    a.mulAssign(gain);
  });
  return s.div(n);
}
const fbm = (x: Node, P: Node, oct: number) => octaves(x, P, oct, 0.5, false);
const ridged = (x: Node, P: Node, oct: number) => octaves(x, P, oct, 0.55, true);

// distances to the nearest and second-nearest feature point of a P-periodic cell grid
function voronoi(x: Node, P: number) {
  const n = floor(x).toVar(), f = fract(x).toVar();
  const d1 = float(8).toVar(), d2 = float(8).toVar();
  Loop(3, 3, ({ i: jj, j: ii }: Node) => {
    const g = vec2(float(ii).sub(1), float(jj).sub(1)).toVar();
    const r = g.add(hash2(n.add(g).mod(vec2(P)))).sub(f).toVar();
    const d = dot(r, r).toVar();
    If(d.lessThan(d1), () => { d2.assign(d1); d1.assign(d); }).ElseIf(d.lessThan(d2), () => { d2.assign(d); });
  });
  return sqrt(vec2(d1, d2));
}

export class FoamTextureCompute {
  tex: THREE.StorageTexture;

  constructor(renderer: THREE.WebGPURenderer, size = 1024) {
    const tex = (this.tex = new THREE.StorageTexture(size, size)); // rgba8unorm
    tex.wrapS = tex.wrapT = THREE.RepeatWrapping;
    tex.generateMipmaps = true; // generated by three when the texture is next sampled after the store
    tex.minFilter = THREE.LinearMipmapLinearFilter;
    tex.magFilter = THREE.LinearFilter;
    tex.anisotropy = 8;
    const node = Fn(() => {
      const x = instanceIndex.mod(size), y = instanceIndex.div(size);
      const uv = vec2(float(x).add(0.5).div(size), float(y).add(0.5).div(size)).toVar();
      // domain-warped ridged noise: veins (low values) where foam lingers
      const w = vec2(fbm(uv.mul(3), vec2(3), 4), fbm(uv.mul(3).add(7.7), vec2(3), 4)).toVar();
      const q = uv.add(w.mul(0.08)).toVar();
      const vein = ridged(q.mul(5), vec2(5), 5).toVar(); // 0 on veins
      const blob = fbm(q.mul(4).add(1.3), vec2(4), 5).mul(0.5).add(0.5).toVar();
      const T = clamp(vein.mul(1.35).mul(0.6).add(blob.mul(0.55)).sub(0.08), 0, 1).toVar();
      // bubbles: small cells with bright rims
      const v = voronoi(uv.mul(90), 90).toVar();
      const bub = smoothstep(0, 0.35, v.y.sub(v.x)).mul(0.45).add(0.55).toVar();
      bub.mulAssign(fbm(uv.mul(40), vec2(40), 3).mul(0.5).add(0.5).mul(0.15).add(0.85));
      // streaks: anisotropic noise, 1:8 along x
      const s = vec2(uv.x.mul(2), uv.y.mul(16));
      const streak = fbm(s, vec2(2, 16), 5).mul(0.5).add(0.5).toVar();
      const sr = ridged(vec2(uv.x.mul(3), uv.y.mul(24)).add(w.mul(0.5)), vec2(3, 24), 4).toVar();
      const S = clamp(streak.mul(0.55).add(sr.mul(0.6)), 0, 1).toVar();
      // A: connected lace network for the residual foam of gale-force seas: the borders of bubble rafts form a
      // cellular lattice, i.e. the edges (F2 - F1 = 0) of a domain-warped Voronoi diagram
      const q2 = uv.add(w.mul(0.05)).toVar();
      const c1 = voronoi(q2.mul(7), 7).toVar();
      const c2 = voronoi(q2.mul(17).add(3.1), 17).toVar();
      const net = min(c1.y.sub(c1.x).mul(1.7), c2.y.sub(c2.x).mul(2.4).add(0.14));
      textureStore(tex, uvec2(x, y), vec4(T, bub, S, clamp(net, 0, 1)));
    })().compute(size * size);
    renderer.compute(node);
  }
}

// FOAM_GLSL's uniforms: uFoamTex, uWindDir, uFoamStretch (0: isotropic patches, 1: fully streaky, gale)
export interface FoamParams { tex: THREE.Texture; windDir: Node; stretch: Node }

// foamCoverage: cov = vec2(coverage, thickness); f = accumulated whitecap foam density, lace = residual stage-B foam
// network (gale force) drawn as thin lines along the wind, act = active breaking. Also returns GL's globals: bump
// (foamBump, relief of the bubble mass) and covA (foamCovA, stage-A coverage, for calibration). Derivatives and
// implicit-LOD samples are taken first and the early return is a select at the end (WGSL uniformity).
export function foamCoverage(fp: FoamParams, xz: Node, f0: Node, lace0: Node, act0: Node, _dist: Node) {
  const f = float(f0).toVar(), lace = float(lace0).toVar(), act = float(act0).toVar();
  const w = vec2(fp.windDir).toVar(), st = fp.stretch;
  const tex = (uv: Node) => texture(fp.tex, uv).toVar();
  const p = vec2(dot(xz, w), dot(xz, vec2(w.y.negate(), w.x))).toVar();
  // derivatives first: they must be evaluated in uniform control flow
  const dpx = dFdx(p).toVar(), dpy = dFdy(p).toVar();
  const a = tex(p.div(5.5));
  const b = tex(p.div(1.9).add(vec2(0.37, 0.71)));
  const s = tex(vec2(p.x.div(45), p.y.div(15)).add(vec2(0.13, 0.5)));
  // large-scale structure stretches along the wind as it strengthens (wind rows of foam)
  const big = tex(vec2(p.x.div(st.mul(5).add(1).mul(37)), p.y.div(37)).add(vec2(0.61, 0.27)));
  // a crest breaks in segments of a few metres, not along its whole length
  const seg = tex(vec2(p.x.div(6), p.y.div(8)).add(vec2(0.43, 0.19))).r.toVar();
  // wind rows: bands ~60 m long and a few metres wide along the wind (Langmuir convergence lines)
  const wr = tex(vec2(p.x.div(140), p.y.div(24).add(big.g.sub(0.5).mul(0.15))).add(vec2(0.71, 0.37))).b.toVar();
  // filament-scale threshold: foam structure lives at 0.3-2 m; the 37 m field only modulates
  const fineT = smoothstep(0.1, 0.5, max(length(dpx), length(dpy)));
  const T0 = big.r.mul(0.18).add(a.r.mul(0.42)).add(mix(b.r, 0.5, fineT).mul(0.4)).toVar();
  const T = mix(T0, mix(T0, s.b.mul(0.8).add(big.g.mul(0.25)), 0.45), st).toVar();
  const dT = vec2(dFdx(T), dFdy(T)).toVar();
  const fwT = abs(dT.x).add(abs(dT.y)).toVar();
  // footprint of a pixel in metres (geometric mean of the axes: what anisotropic filtering resolves)
  const fpm = sqrt(length(dpx).mul(length(dpy))).toVar();
  const fpmMax = max(length(dpx), length(dpy)).toVar();
  const fineA = smoothstep(0.1, 0.5, fpmMax).toVar();
  const pl = vec2(p.x.div(st.mul(6).add(1)), p.y).add(vec2(a.r, b.r).sub(0.5).mul(mix(0.6, 0.25, st))).toVar();
  const va = tex(pl.div(4.2).add(vec2(0.21, 0.83))).a;
  const vb = tex(pl.div(1.5).add(vec2(0.57, 0.11))).a;
  const vein = va.mul(0.6).add(vb.mul(0.4).mul(smoothstep(0.08, 0.3, fpmMax).oneMinus())).add(smoothstep(0.08, 0.3, fpmMax).mul(0.2)).toVar();
  const fwV = fwidth(vein).toVar();
  const none = f.lessThan(0.003).and(lace.lessThan(0.003)).and(act.lessThan(0.003));
  // densities in [0, 1): residual (stage B, seconds to tens of seconds) and active breaking (stage A)
  const F = exp(f.mul(-1.3)).oneMinus().toVar();
  const A = min(exp(act.mul(-2)).oneMinus().mul(mix(0.5, 1, smoothstep(0.25, 0.6, seg))).mul(1.2), 1).toVar();
  // coverage = P(pattern < density): foam fills the low values of a pattern field first.
  //  Pa, active froth: metre-scale churn plus the raft network, so the rim of a breaking crest frays into filaments
  //      and specks, and only the core is solid (with holes)
  //  Pr, residual foam: the raft network dominates, so decaying foam opens up into lace and marbling
  const Pa = clamp(T.mul(0.8).add(vein.mul(0.35).mul(smoothstep(0.5, 0.9, A).oneMinus())).sub(0.12), 0, 1);
  const Pr = clamp(vein.mul(0.85).add(T.mul(0.3)).sub(0.1), 0, 1);
  const far = smoothstep(0.4, 1.6, fpm).toVar();
  // crisp froth edges near, softening only as the structure becomes sub-pixel
  const edge = fwT.mul(0.6).add(0.035).add(fwV.mul(0.4)).add(far.mul(0.2)).add(fineA.mul(0.12)).toVar();
  // residual foam gathers into wind rows (streaks along the wind) as the gale strengthens (ragged edges: the
  // metre-scale structure frays the rows)
  const wrr = wr.add(a.r.sub(0.5).mul(0.22)).add(b.r.sub(0.5).mul(0.12)).toVar();
  const Fs = F.mul(mix(1, pow(smoothstep(0.2, 0.7, wrr), 2).mul(1.6).add(0.25), st)).toVar();
  // a bubble raft never fills its cells: the centres stay open, so old foam stays a network (very dense old foam,
  // as in a gale, does fill most of its cells)
  const mA = A.mul(1.08).sub(Pa).toVar();
  const mR = Fs.mul(mix(0.62, 0.9, smoothstep(0.5, 0.95, F))).sub(Pr).toVar();
  const covA = smoothstep(edge.negate(), edge, mA).mul(smoothstep(0.08, 0.22, A)).toVar();
  // residual foam is a thinner bubble raft, translucent, and thins as it ages into a film that takes the water's
  // tint (below a minimum density old foam is an invisible film: no isolated specks on pattern minima)
  const eR = max(edge, max(0.12, fwV.mul(1.5))).toVar();
  const fsOn = smoothstep(0.12, 0.3, Fs).toVar();
  const covR = smoothstep(eR.negate(), eR, mR).mul(mix(0.45, 0.92, smoothstep(0.15, 0.7, F))).toVar();
  covR.mulAssign(fsOn);
  // where the raft network is unresolved, its mean coverage
  covR.assign(mix(covR, clamp(Fs.mul(0.25), 0, 1).mul(0.85).mul(fsOn), smoothstep(0.1, 0.25, fwV.mul(0.85).add(fwT.mul(0.3)))));
  // far away the structure is sub-pixel: the expected coverage (energy conserving)
  covA.assign(mix(covA, clamp(A.mul(0.95).mul(seg.mul(0.6).add(0.7)), 0, 1), far));
  covR.assign(mix(covR, clamp(Fs.mul(0.4), 0, 1).mul(0.85).mul(fsOn), far));
  const cov = max(covA, covR).toVar();
  // residual lace: thin vein lines, stretched along the wind, thicker as the gale strengthens
  const lc = float(0).toVar();
  If(lace.greaterThan(0.003), () => {
    // lace persists only where foam actually was (old foam f), patchy at the wind-row scale
    const rafts = smoothstep(0.01, 0.15, f).mul(smoothstep(0.15, 0.6, big.b)).mul(smoothstep(0.35, 0.65, wrr)).toVar();
    const wid = lace.mul(0.18).add(0.05).mul(rafts.add(0.6)).toVar();
    // a translucent bubble film, not opaque paint; once the lines are thinner than ~2.5 px they fade to their mean
    // coverage instead of breaking into hairline confetti
    const lcMean = lace.mul(0.08).mul(rafts);
    const lc0 = smoothstep(wid.mul(0.4), wid.mul(1.6), vein).oneMinus().mul(smoothstep(0, 0.08, lace)).mul(rafts).mul(0.28);
    lc.assign(mix(lcMean, lc0, smoothstep(1.5, 3, wid.div(max(fwV, 1e-4))).mul(far.oneMinus())));
  });
  const bub = mix(a.g.mul(0.45).add(b.g.mul(0.35)).add(big.r.mul(0.2)), 0.8, far);
  // optical thickness: dense where the foam far exceeds its threshold, thin near its edges
  const thick = mix(
    max(smoothstep(0, 0.3, mA), smoothstep(0, 0.3, mR).mul(0.6)),
    max(mix(0.35, 0.85, smoothstep(0.1, 0.6, A)).mul(mix(0.6, 1, seg)), clamp(Fs.mul(0.45).mul(1.3), 0, 1)),
    far,
  ).mul(bub).toVar();
  // churned texture inside dense whitecaps: brightness varies with bubble size, coverage stays solid
  thick.mulAssign(mix(smoothstep(0.2, 0.8, b.g.mul(0.6).add(a.g.mul(0.4))).mul(0.4).add(0.6), 1, far));
  // relief of the bubble mass: world-space slope of the structure field (treated as ~15 cm of height), recovered
  // from screen derivatives (inverse of mat2(dpx.x, dpy.x, dpx.y, dpy.y) times dT), for side-lit shading of the foam
  const det = dpx.x.mul(dpy.y).sub(dpy.x.mul(dpx.y)).toVar();
  const ok = abs(det).greaterThan(1e-12);
  const detS = select(ok, det, float(1));
  const inv = vec2(dpy.y.mul(dT.x).sub(dpx.y.mul(dT.y)), dpx.x.mul(dT.y).sub(dpy.x.mul(dT.x))).div(detS);
  const grad = clamp(select(ok, inv, vec2(0)).mul(0.4), vec2(-1.5), vec2(1.5)).mul(far.oneMinus()).toVar();
  const bump = w.mul(grad.x).add(vec2(w.y.negate(), w.x).mul(grad.y));
  // caps fade as they age downwind; lace is a thin translucent bubble film
  thick.mulAssign(mix(0.85, 1, A.div(A.add(F).add(1e-3))));
  // fresh caps have an opaque white core; dense old foam stays a solid raft
  thick.assign(max(thick, covA.mul(smoothstep(0.25, 0.6, A)).mul(mix(0.55, 0.95, a.r.mul(0.5).add(seg.mul(0.5))))));
  thick.assign(max(thick, smoothstep(0.4, 0.85, Fs).mul(smoothstep(0, 0.2, mR)).mul(mix(0.3, 0.65, smoothstep(0.05, 0.3, A)))));
  thick.assign(max(thick, lc.mul(0.5)));
  return {
    cov: select(none, vec2(0), vec2(max(cov, lc), thick)).toVar(),
    bump: select(none, vec2(0), bump).toVar(),
    covA: select(none, float(0), covA).toVar(),
  };
}
